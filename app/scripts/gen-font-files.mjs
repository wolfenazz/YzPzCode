// Generates src/utils/bundledFontFiles.ts: for every face of the font catalog
// that is `bundled`, the @fontsource woff2 files to ship (Latin and Arabic
// subsets, the weights nearest 400 and 700) as lazy `?url` imports, with each
// subset's unicode-range. Run after changing the catalog:
//   node scripts/gen-font-files.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const catalogSource = readFileSync(new URL('src/utils/writing/fontCatalog.ts', root), 'utf8');
const { outputText } = ts.transpileModule(catalogSource, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
const { FONT_CATALOG } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);

const slugOf = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const WANT = [400, 700];
const lines = [];
const missing = [];

for (const font of FONT_CATALOG.filter((entry) => entry.source === 'bundled')) {
  const slug = slugOf(font.name);
  const dir = new URL(`node_modules/@fontsource/${slug}/`, root);
  if (!existsSync(new URL('package.json', dir))) {
    missing.push(font.name);
    continue;
  }
  const unicode = JSON.parse(readFileSync(new URL('unicode.json', dir), 'utf8'));
  const faces = [];
  for (const subset of ['latin', 'arabic']) {
    if (subset === 'arabic' && !font.arabic) continue;
    if (!unicode[subset]) continue;
    const weights = [];
    for (let weight = 100; weight <= 900; weight += 100) {
      if (existsSync(new URL(`files/${slug}-${subset}-${weight}-normal.woff2`, dir))) weights.push(weight);
    }
    if (weights.length === 0) continue;
    const chosen = new Set(WANT.map((target) => weights.reduce((best, weight) => (Math.abs(weight - target) < Math.abs(best - target) ? weight : best), weights[0])));
    for (const weight of [...chosen].sort((a, b) => a - b)) {
      faces.push({ weight, subset, range: unicode[subset] });
    }
  }
  if (faces.length === 0) {
    missing.push(font.name);
    continue;
  }
  const body = faces.map((face) => `    { weight: ${face.weight}, subset: '${face.subset}', range: ${JSON.stringify(face.range)}, load: () => import('@fontsource/${slug}/files/${slug}-${face.subset}-${face.weight}-normal.woff2?url').then((module) => module.default) },`).join('\n');
  lines.push(`  ${JSON.stringify(font.name)}: [\n${body}\n  ],`);
}

const output = `// Generated by scripts/gen-font-files.mjs from the font catalog. Do not edit.
// The woff2 files of every bundled face (Latin and Arabic subsets, regular and bold),
// loaded only when a document uses the face.

export interface BundledFontFace {
  weight: number;
  subset: 'latin' | 'arabic';
  /** CSS unicode-range of the subset. */
  range: string;
  /** Resolves to the file's URL in the app bundle. */
  load: () => Promise<string>;
}

export const BUNDLED_FONT_FILES: Record<string, BundledFontFace[]> = {
${lines.join('\n')}
};
`;
writeFileSync(new URL('src/utils/bundledFontFiles.ts', root), output);
console.log(`wrote ${lines.length} faces`);
if (missing.length) console.log('no files for:', missing.join(', '));
